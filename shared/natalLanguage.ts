export function describeAspect(type:string,a:string,b:string) {
  const first=roles[a], second=roles[b];
  if (!first || !second) return 'Эта линия отмечает измеренный угол между двумя точками карты.';
  const lead=`${first[0]} в астрологии — ${first[1]}, ${second[0]} — ${second[1]}. `;
  const stories: Record<string,string> = {
    conjunction:`В соединении две темы обычно переживаются вместе. Желание ${first[2]} может одновременно побудить ${second[2]}.`,
    sextile:`Секстиль описывает возможность соединить эти качества по собственной инициативе. Если хочется ${first[2]}, полезным первым шагом может стать попытка ${second[2]}.`,
    square:`При квадратуре эти побуждения могут конкурировать. В момент, когда хочется ${first[2]}, одновременно возникает потребность ${second[2]}. Яснее становится после решения, чему уделить внимание сначала.`,
    trine:`Тригон связывают с лёгкостью сочетания двух навыков. Например, ты можешь без долгой подготовки ${first[2]} и сразу ${second[2]}.`,
    opposition:`Оппозиция описывает две стороны выбора. В одной ситуации хочется ${first[2]}, в другой — ${second[2]}. Можно договориться о времени для каждого из этих шагов.`,
  };
  return lead+(stories[type] ?? '');
}
